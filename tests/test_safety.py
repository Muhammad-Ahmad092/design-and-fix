class JunctionTests(TempTree):  # review I1
    def test_link_dir_detected_by_real_path_when_islink_is_false(self):
        # A junction is a directory whose real path is elsewhere while os.path.islink is False.
        put(self.d, "a.py")
        put(self.d, "junc/secret.py", "password = '%s'\n" % _pw())
        outside = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, outside, ignore_errors=True)
        real = os.path.realpath
        junc = os.path.normcase(os.path.join(os.path.realpath(self.d), "junc"))

        def fake_realpath(p, *a, **k):
            r = real(p, *a, **k)
            return outside if os.path.normcase(r) == junc else r

        from unittest import mock
        with mock.patch("dfscan.walker.os.path.realpath", side_effect=fake_realpath):
            res = walk_result(self.d)
        self.assertEqual([f.rel for f in res.files], ["a.py"])
        self.assertEqual(res.skipped, [{"path": "junc", "reason": "symlink_outside"}])

    @unittest.skipUnless(sys.platform == "win32", "NTFS junctions are Windows-only")
    def test_real_junctions_outside_and_self_loop(self):
        import _winapi
        outside = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, outside, ignore_errors=True)
        put(outside, "secret.py", "password = '%s'\n" % _pw())
        put(self.d, "a.py")
        links = [os.path.join(self.d, "junc"), os.path.join(self.d, "self")]
        try:
            _winapi.CreateJunction(outside, links[0])
            _winapi.CreateJunction(self.d, links[1])
        except OSError as exc:
            self.skipTest("cannot create junctions: %s" % exc)
        for link in links:  # remove the junctions first so cleanup never follows them
            self.addCleanup(lambda p=link: os.path.isdir(p) and os.rmdir(p))
        res = walk_result(self.d)
        self.assertEqual([f.rel for f in res.files], ["a.py"])
        self.assertEqual(res.skipped, [{"path": "junc", "reason": "symlink_outside"}])
        r = scan(self.d, use_git=False)
        self.assertFalse([s for s in r["signals"] if s["file"].startswith(("junc", "self"))])



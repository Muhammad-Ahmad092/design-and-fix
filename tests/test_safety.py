def _rand_secret(n, seed):
    """Random-looking generic secret assembled at runtime."""
    import random
    rng = random.Random(seed)
    return "".join(rng.choice("abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789")
                   for _ in range(n))



#!/usr/bin/env python3
"""
gen_rule_docs.py - render docs/rules.md from the scanner rule registry.

Usage:
    python gen_rule_docs.py           write docs/rules.md
    python gen_rule_docs.py --check   exit 1 when docs/rules.md differs from the generated text

Measured precision comes from evals/precision.md when it exists, else from
evals/precision-baseline.md (then labelled as the baseline). The output is deterministic (LF).
"""
from __future__ import annotations

import argparse
import os
import sys
from typing import Dict, List, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from dfscan import report as _report  # noqa: E402,F401  (importing it registers every rule)
from dfscan import registry  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT_PATH = os.path.join(REPO, "docs", "rules.md")
PRECISION = os.path.join(REPO, "evals", "precision.md")
BASELINE = os.path.join(REPO, "evals", "precision-baseline.md")
BACKSLASH = chr(92)


def _cells(line: str) -> List[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse_precision(text: str) -> Dict[str, Tuple[str, str]]:
    """Return {rule id: (precision text, sample n)} from the 'Precision per rule' table.

    Rows whose precision is not a percentage (for example `n/a`) are left out (unmeasured)."""
    out = {}  # type: Dict[str, Tuple[str, str]]
    header = None  # type: Optional[List[str]]
    for line in text.splitlines():
        if not line.startswith("|"):
            header = None
            continue
        cells = _cells(line)
        if header is None:
            if cells and cells[0] == "Rule" and "Precision" in cells and "Sample n" in cells:
                header = cells
            continue
        if set(line.replace("|", "").strip()) <= set("-: "):
            continue
        row = dict(zip(header, cells))
        prec, n = row.get("Precision", ""), row.get("Sample n", "")
        if prec.endswith("%") and n.isdigit() and int(n) > 0:
            out[cells[0]] = (prec, n)
    return out


def _cell(text: str) -> str:
    return str(text).replace(chr(10), " ").replace("|", BACKSLASH + "|").strip()


def render() -> str:
    baseline = not os.path.isfile(PRECISION)
    src = BASELINE if baseline else PRECISION
    label = "evals/precision-baseline.md" if baseline else "evals/precision.md"
    measured = {}  # type: Dict[str, Tuple[str, str]]
    if os.path.isfile(src):
        with open(src, "r", encoding="utf-8") as fh:
            measured = parse_precision(fh.read())
    out = ["# Rule reference", "",
           "Generated by `skills/design-and-fix/scripts/gen_rule_docs.py` from the scanner rule "
           "registry. Do not edit by hand; run the generator after changing a rule.", "",
           "Measured precision is the share of sampled signals a reviewer labelled true "
           "(`n` is the sample size; `unsure` labels are excluded) from `%s`%s. Rules with no "
           "measurement show `unmeasured`." % (
               label, " (the baseline study)" if baseline else ""), "",
           "Note: `no-version-prefix` fires on small unversioned services (internal or "
           "server-rendered apps that do not need versions); it is always low confidence.", "",
           "Default `off` rules are dropped from the scan unless the config enables them with "
           "`\"rules\": {\"<id>\": {\"enabled\": true}}`; the scan lists them in "
           "`summary.default_off_rules` and `notes`.", "",
           "Rules: %d" % len(registry.RULES), "",
           "| Rule | Default | Category | Default severity | Confidence | Languages | "
           "Description | Limitations | Remediation | Measured precision%s |" % (
               " (baseline)" if baseline else ""),
           "|---|---|---|---|---|---|---|---|---|---|"]
    for rid in sorted(registry.RULES):
        m = registry.RULES[rid]
        prec = "%s (n=%s)" % measured[rid] if rid in measured else "unmeasured"
        out.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            rid, "on" if m.default_enabled else "off", _cell(m.category), m.default_severity,
            m.confidence, _cell(", ".join(sorted(m.languages))), _cell(m.description),
            _cell(m.limitations), _cell(m.remediation), prec))
    return "\n".join(out) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="Exit 1 when docs/rules.md is not up to date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        try:
            with open(OUT_PATH, "r", encoding="utf-8", newline="") as fh:
                current = fh.read()  # type: Optional[str]
        except OSError:
            current = None
        if current != text:
            print("docs/rules.md is out of date; run: python skills/design-and-fix/scripts/"
                  "gen_rule_docs.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

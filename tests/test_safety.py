class MaskingLeakTests(TempTree):
    def test_bare_provider_tokens_masked(self):
        for name in ("stripe", "github", "slack", "jwt"):
            tok = _tokens()[name]
            out = mask_secrets("a %s b" % tok)
            self.assertNotIn(tok, out, name)
            self.assertEqual(out, "a *** b", name)

    def test_query_and_header_secrets_masked(self):
        t = _tokens()
        out = mask_secrets('requests.get("https://h.test/x?id=1&api_key=%s&b=2")' % t["query"])
        self.assertNotIn(t["query"], out)
        self.assertIn("id=1", out)
        self.assertNotIn(t["query"], mask_secrets("u = '/p?token=%s'" % t["query"]))
        self.assertNotIn(t["bearer"], mask_secrets("h = 'Authorization: Bearer %s'" % t["bearer"]))
        self.assertNotIn(t["bearer"], mask_secrets('{"Authorization": "%s"}' % t["bearer"]))
        self.assertEqual(mask_secrets("page=2&sort=name"), "page=2&sort=name")

    def test_end_to_end_no_raw_secret_in_output(self):
        t = _tokens()
        nl = chr(10)
        put(self.d, "src/dao.py",
            "db.execute(\"SELECT * FROM t WHERE k='\" + k + \"' \" + '%s')" % t["stripe"] + nl)
        put(self.d, "src/net.py",
            "import requests" + nl
            + 'requests.get("https://h.test/x?token=%s&key=%s")' % (t["github"], t["query"]) + nl)
        put(self.d, "src/h.js",
            'fetch("https://h.test", {headers: {Authorization: "Bearer %s"}, x: "%s"})'
            % (t["bearer"], t["slack"] + " " + t["jwt"]) + nl)
        r = scan(self.d, use_git=False)
        blob = json.dumps(r) + render_markdown(r)
        for name, tok in t.items():
            self.assertNotIn(tok, blob, name)
        code, out = run_cli(self.d, "--no-git", "--quiet")
        code2, md = run_cli(self.d, "--no-git", "--quiet", "--format", "markdown")
        for name, tok in t.items():
            self.assertNotIn(tok, out, name)
            self.assertNotIn(tok, md, name)


